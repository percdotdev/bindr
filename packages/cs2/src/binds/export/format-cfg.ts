import { formatBindLines } from '@workspace/cs2/binds/export/format-bind';
import { formatBindCfgNotes } from '@workspace/cs2/binds/export/format-cfg-notes';
import type { BindCategory, BindEntry } from '@workspace/cs2/binds/model/types';
import {
  BIND_CATEGORY_LABELS,
  BIND_CATEGORY_ORDER,
} from '@workspace/cs2/binds/recommended/categories';

function groupBindsByCategory(binds: BindEntry[]) {
  const grouped = new Map<BindCategory | 'other', BindEntry[]>();

  for (const bind of binds) {
    const bucket = bind.category ?? 'other';
    const current = grouped.get(bucket) ?? [];
    current.push(bind);
    grouped.set(bucket, current);
  }

  return grouped;
}

export function formatBindBody(binds: BindEntry[]): string[] {
  if (binds.length === 0) {
    return ['// No binds configured'];
  }

  const grouped = groupBindsByCategory(binds);
  const sections: string[] = [];

  for (const category of BIND_CATEGORY_ORDER) {
    const categoryBinds = grouped.get(category);
    if (!categoryBinds?.length) {
      continue;
    }

    sections.push(`// ${BIND_CATEGORY_LABELS[category]}`);
    sections.push(formatBindLines(categoryBinds));
    sections.push('');
  }

  const uncategorized = grouped.get('other');
  if (uncategorized?.length) {
    sections.push('// Custom');
    sections.push(formatBindLines(uncategorized));
    sections.push('');
  }

  sections.push(formatBindCfgNotes().trimEnd());

  return sections;
}

export function formatBindCfg(binds: BindEntry[]): string {
  if (binds.length === 0) {
    return '// No binds configured\n';
  }

  const sections = [
    '// Generated by Bindr — paste into autoexec.cfg or run in console',
    '',
    ...formatBindBody(binds),
  ];

  return `${sections.join('\n')}\n`;
}
